export const GTBI_FORMULA_NOTES = [
  "YLD (Years Lived with Disability) = Incidents × Disability Weight × Duration, per exposure type.",
  "YLL (Years of Life Lost) = Deaths × 73.8 (standard life expectancy), per exposure type.",
  "TBU (Trauma Burden Unit), per country-year = ΣYLL + ΣYLD + Σ(Severity Weight × Exposure % / 100) across every exposure type recorded for that country-year.",
  "Burden Rate = (TBU / Population) × 100,000.",
  "GTBI = 100 × (1 − e^(−Burden Rate / 100)), so the composite score saturates toward 100 as burden rate grows.",
  "Trauma Level bands (Low / Moderate / High / Severe) are applied to the 0–100 GTBI score; the source workbook grades individual exposure-type events on its own severity scale, but doesn't define country-year-level bands, so these thresholds (<25 / <50 / <75 / ≥75) are the Observatory's own convention pending confirmation from the data owner.",
];

